std::uint8_t break_class(char32_t c) {
    if (c < 0x300) return c == U' ' ? kBreakSpace : (c == U'-' ? kBreakHyphen : kBreakOther);
    int lo = 0, hi = kRangeCount - 1;
    while (lo <= hi) {
        const int mid = (lo + hi) >> 1;
        if (c < kRanges[mid].first) hi = mid - 1;
        else if (c > kRanges[mid].last) lo = mid + 1;
        else return kRanges[mid].bits;
    }
    return kBreakOther;
}

