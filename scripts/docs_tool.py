#!/usr/bin/env python3
"""Documentation tool for NNHGE (standard library only).

  python3 scripts/docs_tool.py check            # fail on broken relative links in Markdown files
  python3 scripts/docs_tool.py wiki <wiki-dir>  # regenerate the GitHub wiki pages into <wiki-dir>

The repository's Markdown (docs/, specs/, README.md, CONTRIBUTING.md) is the source of truth.
The wiki is generated from it: never edit wiki pages by hand. See docs/process/documentation.md.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO_URL = "https://github.com/rafarvns/nnhge"
GENERATED_MARK = "<!-- generated by scripts/docs_tool.py: edit the source file in the repository -->"

# Sections of the wiki: (source folder, page prefix, sidebar title). Order = sidebar order.
SECTIONS = [
    ("docs/guides", "Guide", "Guides"),
    ("docs/api", "API", "API reference"),
    ("docs/architecture", "Architecture", "Architecture"),
    ("docs/process", "Process", "How we work"),
    ("docs/tech", "Tech", "Technology"),
    ("specs", "Spec", "Specs"),
]
SINGLE_PAGES = {
    "README.md": "Home",
    "CONTRIBUTING.md": "Contributing",
    "docs/ROADMAP.md": "Roadmap",
    "docs/REFERENCES.md": "References",
}
SKIP_DIRS = {"build", ".git", "_deps"}
LINK_RE = re.compile(r"(!?)\[([^\]]*)\]\(([^)\s]+)\)")


def words_title(stem: str) -> str:
    return "-".join(part[:1].upper() + part[1:] for part in re.split(r"[-_]", stem) if part)


def page_name(rel: str) -> str | None:
    """Wiki page name for a repository Markdown path, or None if it isn't published."""
    if rel in SINGLE_PAGES:
        return SINGLE_PAGES[rel]
    for folder, prefix, _ in SECTIONS:
        if not rel.startswith(folder + "/"):
            continue
        inner = rel[len(folder) + 1 :]
        if "_templates/" in inner:
            return None
        if inner == "README.md":
            return prefix if prefix != "Spec" else "Specs"
        stem = inner[: -len(".md")]
        if prefix == "Spec":  # specs/001-slug/spec.md -> Spec-001-Slug, plan.md -> Spec-001-Slug-Plan
            folder_name, _, file_stem = stem.partition("/")
            suffix = "" if file_stem == "spec" else "-" + words_title(file_stem)
            return f"Spec-{words_title(folder_name)}{suffix}"
        return f"{prefix}-{words_title(stem.replace('/', '-'))}"
    return None


def markdown_files() -> list[Path]:
    """Every Markdown file in the repository except build output (templates and .claude included)."""
    return [p for p in sorted(ROOT.rglob("*.md"))
            if not any(part in SKIP_DIRS for part in p.relative_to(ROOT).parts[:-1])]


def resolve(source: Path, target: str) -> tuple[Path, str]:
    path_part, _, anchor = target.partition("#")
    return (source.parent / path_part).resolve(), anchor


def is_external(target: str) -> bool:
    return target.startswith(("http://", "https://", "mailto:", "#"))


def cmd_check() -> int:
    broken = 0
    for path in markdown_files():
        for match in LINK_RE.finditer(path.read_text(encoding="utf-8")):
            target = match.group(3)
            if is_external(target):
                continue
            resolved, _ = resolve(path, target)
            if not resolved.exists():
                print(f"{path.relative_to(ROOT)}: broken link -> {target}")
                broken += 1
    print(f"{len(markdown_files())} files checked, {broken} broken links")
    return 1 if broken else 0


def rewrite_links(source: Path, text: str) -> str:
    def replace(match: re.Match) -> str:
        bang, label, target = match.groups()
        if is_external(target):
            return match.group(0)
        resolved, anchor = resolve(source, target)
        try:
            rel = resolved.relative_to(ROOT).as_posix()
        except ValueError:
            return match.group(0)
        name = page_name(rel) if rel.endswith(".md") else None
        if name and not bang:
            return f"[{label}]({name}{'#' + anchor if anchor else ''})"
        kind = "tree" if resolved.is_dir() else ("raw" if bang else "blob")
        return f"{bang}[{label}]({REPO_URL}/{kind}/main/{rel}{'#' + anchor if anchor else ''})"

    return LINK_RE.sub(replace, text)


def heading(rel: str) -> str:
    """First '# ' heading of a file, used as its sidebar label."""
    for line in (ROOT / rel).read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return rel


def sidebar(pages: dict[str, str]) -> str:
    lines = ["**[Home](Home)**", "", "- [Roadmap](Roadmap)", "- [Contributing](Contributing)",
             "- [References](References)", ""]
    for folder, _, title in SECTIONS:
        rels = [rel for rel in pages if rel.startswith(folder + "/")]
        if not rels:
            continue
        # Folder overview (README) first, then the rest by path.
        rels.sort(key=lambda rel: (not rel.endswith("/README.md"), rel))
        lines += [f"**{title}**", ""]
        for rel in rels:
            label = "Overview" if rel == f"{folder}/README.md" else heading(rel)
            lines.append(f"- [{label}]({pages[rel]})")
        lines.append("")
    return "\n".join(lines)


def cmd_wiki(out_dir: str) -> int:
    out = Path(out_dir).resolve()
    if not out.is_dir():
        print(f"wiki directory not found: {out} (clone {REPO_URL}.wiki.git first)")
        return 1
    pages: dict[str, str] = {}
    for path in markdown_files():
        rel = path.relative_to(ROOT).as_posix()
        name = page_name(rel)
        if name:
            pages[rel] = name

    written = set()
    for rel, name in pages.items():
        source = ROOT / rel
        body = rewrite_links(source, source.read_text(encoding="utf-8"))
        header = (f"{GENERATED_MARK}\n> Generated from [`{rel}`]({REPO_URL}/blob/main/{rel}). "
                  "Edit that file in the repository; changes here are overwritten.\n\n")
        (out / f"{name}.md").write_text(header + body, encoding="utf-8", newline="\n")
        written.add(f"{name}.md")
    (out / "_Sidebar.md").write_text(sidebar(pages), encoding="utf-8", newline="\n")
    (out / "_Footer.md").write_text(
        f"NNHGE · zlib license · generated from [the repository docs]({REPO_URL}/tree/main/docs)\n",
        encoding="utf-8", newline="\n")
    written |= {"_Sidebar.md", "_Footer.md"}

    removed = 0
    for stale in out.glob("*.md"):
        if stale.name not in written and stale.read_text(encoding="utf-8").startswith(GENERATED_MARK):
            stale.unlink()
            removed += 1
    print(f"wiki: {len(pages)} pages written, {removed} stale pages removed")
    return 0


def main(argv: list[str]) -> int:
    if len(argv) >= 2 and argv[1] == "check":
        return cmd_check()
    if len(argv) >= 3 and argv[1] == "wiki":
        return cmd_wiki(argv[2])
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
