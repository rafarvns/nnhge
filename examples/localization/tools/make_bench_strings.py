"""Writes assets/strings/en/bench.strings (spec 029 T7.1): 1 024 keys `bench.k0000`..`bench.k1023` of pseudo-random
English-like text, about 64 KiB with the main file, so the bench's `tr` and its language switch read a table of a real
game's size. Deterministic (a fixed LCG); the output is committed. Base-only keys: the other languages fall back to en.

Usage: python -I make_bench_strings.py <out.strings>
"""
import sys

WORDS = ("lantern road tower flame valley wind keeper dawn night stone river bridge forest gate key map coin shield "
         "sword potion scroll village market merchant traveller guard north south east west old new small great").split()


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    state = 2029
    lines = ["# Generated by tools/make_bench_strings.py: the bench's table (base only).", "", "[bench]"]
    for i in range(1024):
        words = []
        for _ in range(7 + i % 4):
            state = (state * 1103515245 + 12345) & 0x7FFFFFFF
            words.append(WORDS[(state >> 8) % len(WORDS)])
        lines.append('k%04d = "%s."' % (i, " ".join(words).capitalize()))
    open(sys.argv[1], "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
