"""Writes tools/assetc/src/charsets_cjk.cpp: the kyoiku kanji (the 1 006 of the pre-2020 list) and JIS X 0208 level 1
(rows 16-47, 2 965 kanji) as sorted code point tables for the font converter's named sets (spec 029 FR-3).

Sources: JIS level 1 from Python's own EUC-JP codec (rows 16-47 of JIS X 0208); the kyoiku grades from
kanji-data's kanji.json (https://github.com/davidluzgouveia/kanji-data, MIT, "grade" 1-6), a list of facts the
Japanese Ministry of Education publishes. Usage: python -I make_charsets_cjk.py <kanji.json> <out.cpp>
"""
import json
import sys


def jis_level1():
    out = []
    for row in range(0xB0, 0xD0):
        for cell in range(0xA1, 0xFF):
            if row == 0xCF and cell > 0xD3:
                break
            out.append(ord(bytes([row, cell]).decode("euc_jp")))
    return sorted(out)


def kyoiku(path):
    data = json.load(open(path, encoding="utf-8"))
    return sorted(ord(k) for k, v in data.items() if v.get("grade") and 1 <= v["grade"] <= 6)


def table(name, cps):
    lines = []
    line = "   "
    for cp in cps:
        item = " 0x%04X," % cp
        if len(line) + len(item) > 116:
            lines.append(line)
            line = "   "
        line += item
    lines.append(line)
    return "const std::uint16_t %s[%d] = {\n%s\n};\n" % (name, len(cps), "\n".join(lines))


def main():
    kj, out = sys.argv[1], sys.argv[2]
    level1, grades = jis_level1(), kyoiku(kj)
    assert len(level1) == 2965 and len(grades) == 1006
    text = ("// The font converter's CJK named sets (spec 029 FR-3; charsets.hpp): generated by\n"
            "// tools/assetc/scripts/make_charsets_cjk.py (JIS X 0208 level 1 from the EUC-JP codec; the 1 006 kyoiku kanji\n"
            "// of the pre-2020 list from kanji-data, MIT). Do not edit by hand.\n\n"
            "#include \"charsets_cjk.hpp\"\n\nnamespace nnh::assetc {\n\n"
            + table("kKyoiku", grades) + "\n" + table("kJisLevel1", level1) + "\n} // namespace nnh::assetc\n")
    open(out, "w", encoding="utf-8", newline="\n").write(text)


if __name__ == "__main__":
    main()
