NNH_TEST(every_curve_gives_the_frozen_golden_bits) {
    int mismatches = 0;
    for (int c = 0; c < nnh::kEaseCount; ++c) {
        for (int i = 0; i <= 32; ++i) {
            const float v = nnh::ease(static_cast<nnh::Ease>(c), static_cast<float>(i) / 32.0f);
            const std::uint32_t bits = std::bit_cast<std::uint32_t>(v);
            if (bits != kGolden[c][i]) {
                std::printf("  ease %d at %d/32: 0x%08x, golden 0x%08x\n", c, i, static_cast<unsigned>(bits),
                            static_cast<unsigned>(kGolden[c][i]));
                ++mismatches;
            }
        }
    }
    CHECK(mismatches == 0);
}
